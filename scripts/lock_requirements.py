"""Write requirements.lock — the exact versions this venv runs and is tested with. Free.

    .venv\\Scripts\\python.exe scripts\\lock_requirements.py

Why (docs/research/2026-10-15/audit-ops.md OPS-24, reproduced there):
requirements.txt had only open lower bounds and no lock, so a fresh install
pulled whatever was newest — anthropic 1.14.0, a major release on httpx2 that
this app's SDK patching (providers/usage.instrument) was never tested with.

What it pins: exactly what requirements.txt needs, walked through the
installed packages' own metadata (extras and Windows markers included) — not
`pip freeze`, which in this venv still lists torch, transformers and the rest
of what the 2026-09 pivot dropped. yt-dlp is left OUT on purpose: the
platforms change under it, so it is updated deliberately (OPS-25), not frozen.
Run it again after any deliberate upgrade, with the suite green.
"""
import re
import sys
from importlib.metadata import distribution
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from scripts.render import force_utf8_stdout  # noqa: E402
_NOT_LOCKED = {"yt-dlp"}


def _roots() -> list[Requirement]:
    roots = []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = re.sub(r"\s+#.*$", "", line).strip()
        if line and not line.startswith(("#", "-")):
            roots.append(Requirement(line))
    return roots


def locked() -> dict[str, tuple[str, str]]:
    """canonical name -> (the package's own name, its installed version)."""
    found: dict[str, tuple[str, str]] = {}
    walked: set[tuple[str, frozenset]] = set()
    stack = [(r.name, frozenset(r.extras)) for r in _roots()
             if canonicalize_name(r.name) not in _NOT_LOCKED]
    while stack:
        name, extras = stack.pop()
        key = canonicalize_name(name)
        if (key, extras) in walked:
            continue
        walked.add((key, extras))
        dist = distribution(name)
        found[key] = (dist.metadata["Name"], dist.version)
        for spec in dist.requires or []:
            req = Requirement(spec)
            wanted = req.marker is None or any(
                req.marker.evaluate({**default_environment(), "extra": extra})
                for extra in (extras or {""}))
            if wanted and canonicalize_name(req.name) not in _NOT_LOCKED:
                stack.append((req.name, frozenset(req.extras)))
    return found


def main() -> None:
    force_utf8_stdout()          # the house rule for every script that prints
    lines = ["# Generated by scripts/lock_requirements.py from this venv - the exact",
             "# versions the suite passed with. Install: pip install -r requirements.lock,",
             "# then pip install -U yt-dlp (left out on purpose: it must keep up).",
             *(f"{name}=={version}" for name, version in
               sorted(locked().values(), key=lambda nv: nv[0].lower()))]
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"requirements.lock: {len(lines) - 3} packages")


if __name__ == "__main__":
    sys.exit(main())
